"""Project-root anchored paths.

The original repository used CWD-dependent relative paths such as
``./dataset/O1_3p5/train`` or ``../../LWLM/dataset/...`` which only worked when
a script was launched from exactly one directory.  Every path in this refactor
is derived from the project root (the folder that contains the ``lwlm``
package), so scripts and the notebook work from any working directory.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

# .../LWLM/lwlm/paths.py -> parents[0] = lwlm, parents[1] = LWLM (project root)
PROJECT_ROOT = Path(__file__).resolve().parents[1]

# Allow an override, e.g. for Colab: os.environ["LWLM_ROOT"] = "/content/LWLM"
if os.environ.get("LWLM_ROOT"):
    PROJECT_ROOT = Path(os.environ["LWLM_ROOT"]).resolve()


def root() -> Path:
    """Project root directory (contains the ``lwlm`` package)."""
    return PROJECT_ROOT


# ---------------------------------------------------------------------------
# Raw DeepMIMO data (user-provided .mat files) - NEVER generated by this repo
# ---------------------------------------------------------------------------
def dataset_dir() -> Path:
    """Folder with the raw DeepMIMO O1_3p5 ``.mat`` files (user-provided)."""
    return PROJECT_ROOT / "Dataset"


def locate_scenario(scenario: str = "O1_3p5") -> Path:
    """Locate the raw DeepMIMO scenario folder inside ``Dataset/``.

    Supports both common download layouts::

        Dataset/O1_3p5/*.mat          (extracted scenario folder)
        Dataset/*.mat                 (loose .mat files directly in Dataset/)

    Returns the folder that should be used as ``DeepMIMOv3.dataset_folder``,
    i.e. the *parent* directory that contains ``<scenario>/``.  If the ``.mat``
    files are loose inside ``Dataset/`` itself, hard links (fallback: copies)
    are placed under ``Dataset/<scenario>/`` so DeepMIMOv3 - which always loads
    ``<dataset_folder>/<scenario>/*.mat`` - finds them without duplicating data.
    """
    d = dataset_dir()
    if not d.exists():
        raise FileNotFoundError(
            f"Dataset folder not found: {d}\n"
            f"Please download the DeepMIMO '{scenario}' scenario from "
            f"https://deepmimo.net/scenarios/o1-scenario/ and extract the .mat "
            f"files into '{d}'."
        )

    scenario_dir = d / scenario
    if scenario_dir.is_dir():
        # Case 1: Dataset/O1_3p5/*.mat
        return d

    mat_files = sorted(d.glob("*.mat"))
    if mat_files:
        # Case 2: loose .mat files inside Dataset/  ->  materialise
        # Dataset/O1_3p5/ with hard links (instant, no data duplication;
        # copies only as a cross-device fallback).
        scenario_dir.mkdir(parents=True, exist_ok=True)
        for mat in mat_files:
            dst = scenario_dir / mat.name
            if dst.exists():
                continue
            try:
                os.link(mat, dst)
            except OSError:
                shutil.copy2(mat, dst)
        return d

    # maybe the scenario folder is nested one level deeper (e.g. Dataset/download/O1_3p5)
    for sub in sorted(d.iterdir()):
        if not sub.is_dir():
            continue
        if (sub / scenario).is_dir():
            return sub
        sub_mats = sorted(sub.glob("*.mat"))
        if sub_mats:
            target = sub / scenario
            target.mkdir(parents=True, exist_ok=True)
            for mat in sub_mats:
                dst = target / mat.name
                if dst.exists():
                    continue
                try:
                    os.link(mat, dst)
                except OSError:
                    shutil.copy2(mat, dst)
            return sub

    raise FileNotFoundError(
        f"No '.mat' files found under '{d}'. Expected '{d}/{scenario}/*.mat' "
        f"or '{d}/*.mat'. Please extract the DeepMIMO '{scenario}' scenario there."
    )


# ---------------------------------------------------------------------------
# Processed data (per-sample .h5py files + index .npy files)
# ---------------------------------------------------------------------------
def processed_dir() -> Path:
    """Root of the converted per-sample dataset (h5py pool + index files)."""
    p = PROJECT_ROOT / "processed"
    p.mkdir(parents=True, exist_ok=True)
    return p


def processed_split_dir(split: str = "train", scenario: str = "O1_3p5") -> Path:
    """``processed/O1_3p5/{split}`` - split in {train, pretrain, test}."""
    return processed_dir() / scenario / split


def bs_folder(bs: int, bw: int, split: str = "train",
              n_sc: int = 128, n_ant: int = 32, scenario: str = "O1_3p5") -> Path:
    """Per-(BS, BW) sample folder, original naming: BS3_128sc_32at_10M."""
    d = processed_split_dir(split, scenario) / f"BS{bs}_{n_sc}sc_{n_ant}at_{bw}M"
    d.mkdir(parents=True, exist_ok=True)
    return d


# ---------------------------------------------------------------------------
# Outputs
# ---------------------------------------------------------------------------
def checkpoints_dir() -> Path:
    d = PROJECT_ROOT / "checkpoints"
    d.mkdir(parents=True, exist_ok=True)
    return d


def results_dir() -> Path:
    d = PROJECT_ROOT / "results"
    d.mkdir(parents=True, exist_ok=True)
    return d


def logs_dir() -> Path:
    d = PROJECT_ROOT / "logs"
    d.mkdir(parents=True, exist_ok=True)
    return d


def index_file(name: str) -> Path:
    """Index .npy files (train.npy / val_1000.npy / pretrain_data.npy) live at
    the root of the processed folder - same relative layout as the original
    repo's ``./dataset/*.npy``."""
    return processed_dir() / name
